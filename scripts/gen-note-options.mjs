// Regenerates supabase/migrations/20260801000002_note_options.sql from src/lib/noteOptions.json.
// Run after editing the options:  node scripts/gen-note-options.mjs
// Then apply the new SQL file to your Supabase project (it is safe to re-run).
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../src/lib/noteOptions.json', import.meta.url), 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const rows = [];
for (const t of src.templates) for (const o of t.options) rows.push(['template', t.id, o]);
for (const m of src.moods) rows.push(['mood', m.id, m.label]);
for (const b of src.bestFor) rows.push(['bestFor', b.id, b.label]);
for (const f of src.foundVia) rows.push(['foundVia', f.id, f.label]);
for (const r of src.reactions) rows.push(['reaction', r.emoji, r.label]);

const sql = `-- GENERATED by scripts/gen-note-options.mjs from src/lib/noteOptions.json. Do not edit by hand.
-- Every message a sender can attach must match a row here, so no free text can get through.
begin;
delete from public.note_options;
insert into public.note_options (kind, key, value) values
${rows.map((r) => `  (${r.map(q).join(', ')})`).join(',\n')};
commit;
`;

writeFileSync(new URL('../supabase/migrations/20260801000002_note_options.sql', import.meta.url), sql);
console.log(`Wrote ${rows.length} note options.`);
